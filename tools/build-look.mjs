// Build js/look.js from the .md files in look/ (LOOK.md first): every JSON object in them, merged in order (later wins).
//   node tools/build-look.mjs        (render-test.mjs runs this before every export)
// palette: { theme: { 'tp.astro.rim': '#hex' } } merged per colour; elements: { id: { tex, shift, ... } } merged per element.
// Texture numbers (positions in the play-bar list) become names, read from js/scenes/texture.js, so reordering the list
// later cannot change a look.
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'look'), OUT = path.join(ROOT, 'js', 'look.js');
// every .md file in look/, LOOK.md first, then the rest alphabetically (so pasting into any of them works)
const FILES = fs.existsSync(DIR) ? fs.readdirSync(DIR).filter(f => f.endsWith('.md')).sort((a, b) => (b === 'LOOK.md') - (a === 'LOOK.md') || a.localeCompare(b)) : [];
const NAMES = [...fs.readFileSync(path.join(ROOT, 'js', 'scenes', 'texture.js'), 'utf8')
  .slice(0, 4000).matchAll(/\{ name: '([^']+)'/g)].map(m => m[1]);

// every top-level { ... } in the text, by brace matching (strings respected), parsed as JSON
function objects(text) {
  const out = []; let depth = 0, start = -1, inStr = false, esc = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inStr) { if (esc) esc = false; else if (ch === '\\') esc = true; else if (ch === '"') inStr = false; continue; }
    if (ch === '"' && depth > 0) inStr = true;
    else if (ch === '{') { if (!depth) start = i; depth++; }
    else if (ch === '}' && depth) { depth--; if (!depth) { const s = text.slice(start, i + 1); try { out.push(JSON.parse(s)); } catch (e) { console.warn(`skipped a block that is not valid JSON (line ${text.slice(0, start).split('\n').length}): ${e.message}`); } } }
  }
  return out;
}

const look = { palette: {}, elements: {} };
const blocks = FILES.flatMap(f => objects(fs.readFileSync(path.join(DIR, f), 'utf8')));
for (const b of blocks) {
  for (const [theme, cols] of Object.entries(b.palette || {})) look.palette[theme] = { ...(look.palette[theme] || {}), ...cols };
  for (const [id, set] of Object.entries(b.elements || {})) {
    const s = { ...(look.elements[id] || {}), ...set };
    if (typeof s.tex === 'number') s.tex = NAMES[s.tex] ?? 'Clay';
    if (!s.tex || s.tex === 'Clay') delete s.tex;
    delete s.shiftBase; delete s.shift;                   // the palette already holds the shifted colours (the sliders start at 0 on top of them)
    if (Object.keys(s).length) look.elements[id] = s; else delete look.elements[id];
  }
}
fs.writeFileSync(OUT, `'use strict';\n// GENERATED by tools/build-look.mjs from look/LOOK.md: edit that file, not this one.\nconst LOOK = ${JSON.stringify(look, null, 2)};\n`);
console.log(`look: ${FILES.join(', ')}: ${blocks.length} block(s) → ${Object.values(look.palette).reduce((n, t) => n + Object.keys(t).length, 0)} colours, ${Object.keys(look.elements).length} element settings → js/look.js`);
